create or replace function public.activate_rdi_rubric_v2(
  p_shortcode text,
  p_name text,
  p_raw_md text,
  p_definition jsonb
)
returns void
language plpgsql
as $$
declare
  next_version integer;
  now_text text := to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
begin
  if not exists (select 1 from public.jobs where shortcode = p_shortcode) then
    return;
  end if;

  select coalesce(max(version), 0) + 1
    into next_version
    from public.rubrics
   where job_shortcode = p_shortcode;

  update public.rubrics
     set active = false
   where job_shortcode = p_shortcode
     and active = true;

  insert into public.rubrics(job_shortcode, version, name, raw_md, definition, weights, active)
  values (
    p_shortcode,
    next_version,
    p_name,
    p_raw_md,
    p_definition,
    '{"principal":25,"environment":20,"scope":20,"writing":15,"tenure":10,"local":10}'::jsonb,
    true
  );

  insert into public.sync_state(key, value, updated_at)
  values ('scoring_epoch:' || p_shortcode, jsonb_build_object('at', now_text), now())
  on conflict (key) do update
    set value = excluded.value,
        updated_at = excluded.updated_at;
end;
$$;

