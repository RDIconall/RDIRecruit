# RDI Hiring Method v2 - Demonstrated Capability, Provenance, and Seat Fit

The core unit of evidence is what this person has actually done. RDIRecruit is not a resume keyword matcher, prestige/title scorer, AI-writing detector, or generic ATS score. It protects interview time by deciding what has been demonstrated, what remains unproven, what should be tested live, and whether a strong person fits a different RDI seat.

## Core questions

1. Is this person actually good?
2. What have they actually demonstrated?
3. Is that demonstrated capability relevant to this seat?
4. Is the application showing their own judgment or synthetic expertise generated by AI?
5. What work or judgment can they remove from Conall and Lara?
6. What remains unproven?
7. What should be tested live?
8. If they are strong but wrong for the applied seat, what RDI seat actually fits them?

## Evidence provenance

Before crediting any substantive answer as capability, ask: where would this person have learned this?

Classify each displayed capability:
- EXPERIENCE_BACKED: the career record shows substantially similar work.
- ADJACENT_PLAUSIBLE: the exact task is not shown, but underlying work could reasonably produce the judgment.
- UNSUPPORTED_EXPERTISE: the answer shows detailed expertise the career history does not show.
- CONTRADICTED: the answer conflicts materially with verified evidence.

An excellent answer is not automatically proven capability. The evaluator must be able to say: "Excellent answer. Career history does not show where they learned this."

## AI/authenticity

AI use itself is not the problem. AI as editor on experience-backed judgment is fine. AI as thought partner on adjacent experience can earn partial/cautious credit and live validation. AI as substitute for experience or judgment is materially misleading when unsupported expertise is submitted as the candidate's own judgment. Do not accuse based on polished prose alone; the evidence mismatch is the important signal.

When both are true - unsupported expertise and likely synthetic authorship - do not credit the capability, raise an integrity/authenticity concern, allow the integrity gate to fail, and generate an aggressive live verification question.

## Scoring architecture

Use dynamic seat-specific dimensions as the primary hiring score. Keep legacy category_scores only for backwards compatibility. Store separately: personQuality, seatFit, seatDimensionScores, evidenceConfidence, integrityGate, otherGateResults, roDiagnostic, alternateSeatSignals, liveValidationQuestions, and summary.

Seat dimensions total 100. Gates override the numeric score. Critical dimension minimums cap below Interview-First. Do not allow an 88 assembled from peripheral strengths to hide failure on the central requirement of the job.

Bands:
- 85+ = strong / interview-first
- 70-84 = viable / interview or validate
- 55-69 = hold
- below 55 = pass

## RDI operator read

Across senior/operator seats assess diagnosis, ownership, hands-on depth, adaptability, commercial judgment, system building, status orientation, and portability. Use evidence; do not invent personality assessments.

## Person quality vs seat fit

Separate strong person / strong seat, strong person / wrong seat, promising / not ready, and weak candidate. A strong lab builder applying to clinical operations should surface as strong person - wrong seat, with Laboratory Director as an alternate if evidence supports it.

## RO diagnostic boundary

Preserve Requisite Organization analysis: chronology, first professional role, undergraduate graduation where relevant, career span, progression rate, time-span of discretion, RO strata, and approximate maturation placement. Keep RO_DIAGNOSTIC separate from employment score. Approximate age/maturation placement must not directly add/subtract seat-fit points, trigger interview/pass thresholds, sort candidates, change salary recommendations, or trigger alternate-seat recommendations.

## Live validation questions

For uncertain provenance or synthetic expertise, ask for the last real example, scale, personal decision, what was wrong, numbers/constraints, who disagreed, what changed, and final result.

## Compliance

Use job-relevant evidence only. Never extract, infer, or flag protected or non-job attributes. Career span is an experience/level signal for RO progression-rate analysis; it is not age and must never become a threshold or cutoff.
